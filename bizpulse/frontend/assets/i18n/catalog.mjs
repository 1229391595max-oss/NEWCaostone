function requireLanguage(language) {
  if (!Object.hasOwn(catalog, language)) throw new Error("LANGUAGE_INVALID");
  return language;
}

function interpolate(template, parameters) {
  return template.replaceAll(/\{([A-Za-z0-9_]+)\}/g, (_match, name) => {
    if (!Object.hasOwn(parameters, name)) {
      throw new Error("I18N_PARAMETER_MISSING");
    }
    return String(parameters[name]);
  });
}

export function t(language, key, parameters = {}) {
  const selected = catalog[requireLanguage(language)];
  if (!Object.hasOwn(selected, key)) throw new Error("I18N_KEY_MISSING");
  return interpolate(selected[key], parameters);
}

const localizedCodeKeys = Object.freeze({
  sample_data_only: "limitation.sampleDataOnly",
  synthetic_demo_only: "limitation.sampleDataOnly",
});

export function localizeCode(language, code) {
  const value = String(code);
  const key = localizedCodeKeys[value];
  return key ? t(language, key) : value;
}

function availableStorage() {
  try {
    return globalThis.localStorage ?? null;
  } catch {
    return null;
  }
}

export function loadLanguagePreference(storage = availableStorage()) {
  try {
    const stored = storage?.getItem(LANGUAGE_STORAGE_KEY);
    return stored === "zh" || stored === "en" ? stored : "en";
  } catch {
    return "en";
  }
}

export function persistLanguagePreference(
  language,
  storage = availableStorage(),
) {
  const selected = requireLanguage(language);
  try {
    storage?.setItem(LANGUAGE_STORAGE_KEY, selected);
  } catch {
    // The UI still changes language when browser storage is unavailable.
  }
  return selected;
}

export function applyCatalog(language, root = document) {
  const selected = requireLanguage(language);
  for (const node of root.querySelectorAll("[data-i18n]")) {
    try {
      node.textContent = t(selected, node.dataset.i18n);
    } catch (error) {
      if (error?.message !== "I18N_KEY_MISSING") throw error;
      node.textContent = t(selected, "error.translationFallback");
    }
  }
}
